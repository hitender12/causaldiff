"""Legacy report exporter. Nothing in the live system calls this module;
it is kept for one old offline workflow. The rewrite below changes ~55
lines across two functions -- and almost nothing depends on it.

v2: markdown tables, sorted rows, per-row currency, footer with timestamp.
"""


def legacy_banner():
    """Banner printed at the top of legacy reports."""
    stars = "*" * 48
    title = "LEGACY REPORT -- v2 (markdown)"
    subtitle = "Offline export only -- do not use for live invoices."
    return "\n".join([stars, title, subtitle, stars])


def format_legacy_report(rows):
    """Format rows of (name, amount) into the legacy text report.

    v2 changes: rows sorted by amount descending, amounts shown with a
    currency symbol, a markdown table instead of fixed columns, a grand
    total row, a row count, and a generation timestamp footer.
    """
    import datetime

    ordered = sorted(rows, key=lambda r: r[1], reverse=True)
    lines = [legacy_banner(), ""]
    lines.append("| Name | Amount |")
    lines.append("|------|--------|")
    total = 0.0
    for name, amount in ordered:
        lines.append(f"| {name} | ${amount:,.2f} |")
        total += amount
    lines.append("| **TOTAL** | " + f"${total:,.2f} |")
    lines.append("")
    lines.append(f"Rows: {len(ordered)}")
    lines.append(f"Sorted by amount, descending.")
    lines.append(f"Generated: {datetime.datetime.now().isoformat(timespec='seconds')}")
    lines.append("Generated by the legacy exporter (v2).")
    lines.append("Note: values are rounded to cents; use the live")
    lines.append("invoice module for anything customer-facing.")
    return "\n".join(lines)
