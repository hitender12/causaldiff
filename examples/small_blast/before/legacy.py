"""Legacy report exporter. Nothing in the live system calls this module;
it is kept for one old offline workflow. The rewrite below changes ~55
lines across two functions -- and almost nothing depends on it."""


def legacy_banner():
    """Banner printed at the top of legacy reports."""
    line = "=" * 40
    title = "LEGACY REPORT"
    return f"{line}\n{title}\n{line}"


def format_legacy_report(rows):
    """Format rows of (name, amount) into the legacy text report."""
    out = [legacy_banner(), ""]
    out.append(f"{'Name':<20}{'Amount':>10}")
    out.append("-" * 30)
    total = 0
    for name, amount in rows:
        out.append(f"{name:<20}{amount:>10.2f}")
        total += amount
    out.append("-" * 30)
    out.append(f"{'TOTAL':<20}{total:>10.2f}")
    out.append("")
    out.append(f"Rows: {len(rows)}")
    out.append("Generated by the legacy exporter (v1).")
    return "\n".join(out)
